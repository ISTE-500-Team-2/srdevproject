#!/usr/bin/env python3
"""Embed the authoritative web/index.html file into an Arduino PROGMEM header."""

from __future__ import annotations

import argparse
import gzip
import hashlib
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "web" / "index.html"
OUTPUT = ROOT / "web_ui.h"
DELIMITER = "FIELDNOTE_HTML"


def render_header(html: str) -> str:
    closing_marker = f"){DELIMITER}\""
    if closing_marker in html:
        raise ValueError(f"HTML contains reserved raw-string marker {closing_marker!r}")
    data = html.encode("utf-8")
    compressed = gzip.compress(data, compresslevel=9, mtime=0)
    rows = [", ".join(f"0x{byte:02x}" for byte in compressed[i:i + 16])
            for i in range(0, len(compressed), 16)]
    etag = hashlib.sha256(data).hexdigest()[:16]
    return (
        "// Generated by tools/embed_web.py from web/index.html. Do not edit directly.\n"
        "#pragma once\n\n"
        "#include <Arduino.h>\n\n"
        f"const char kWebUi[] PROGMEM = R\"{DELIMITER}({html}){DELIMITER}\";\n"
        f'const char kWebUiEtag[] = "W/\\"{etag}\\"";\n'
        "const uint8_t kWebUiGzip[] PROGMEM = {\n  "
        + ",\n  ".join(rows) + "\n};\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if web_ui.h is stale")
    args = parser.parse_args()

    expected = render_header(SOURCE.read_text(encoding="utf-8"))
    if args.check:
        actual = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if actual != expected:
            print("web_ui.h is stale; run tools/embed_web.py", file=sys.stderr)
            return 1
        print("web_ui.h matches web/index.html")
        return 0

    OUTPUT.write_text(expected, encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
