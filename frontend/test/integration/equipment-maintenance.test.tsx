import { afterAll, beforeAll, expect, test, vi } from 'vitest';
import { cleanup, fireEvent, render, screen, within, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { MemoryRouter } from 'react-router-dom';
import App from '../../src/App';
import { createBrowserBridge } from '../../../backend/test/helpers/browserBridge';

let bridge: Awaited<ReturnType<typeof createBrowserBridge>>;
beforeAll(async () => { bridge = await createBrowserBridge(); }, 120000);
afterAll(async () => { cleanup(); vi.unstubAllGlobals(); await bridge?.close(); }, 30000);
test('administrator takes equipment down, reviews and moves one booking, cancels another, and restores service', async () => {
  vi.stubGlobal('fetch', bridge.fetch);
  const login = await bridge.fetch('/api/auth/demo', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ role: 'admin' }) });
  expect(login.status).toBe(200);
  const member = (await bridge.pool.query(`SELECT userid FROM "user" WHERE email='demo.member@collaboratory.invalid'`)).rows[0].userid;
  const machines = (await bridge.pool.query(`INSERT INTO equipment(name,status,hourlyrate,waiverrequired) VALUES('Maintenance source','available',12,false),('Maintenance replacement','available',15,false) RETURNING equipmentid`)).rows;
  const source = machines[0].equipmentid, target = machines[1].equipmentid;
  const bookings = (await bridge.pool.query(`INSERT INTO reservation(userid,equipmentid,location,starttime,endtime,status)
    SELECT $1,$2,'Test',(NOW()+n*INTERVAL '1 day') AT TIME ZONE 'UTC',(NOW()+n*INTERVAL '1 day'+INTERVAL '1 hour') AT TIME ZONE 'UTC','confirmed' FROM generate_series(2,3) n RETURNING reservationid`, [member, source])).rows;
  render(<MemoryRouter initialEntries={[`/admin/equipment/${source}`]}><App /></MemoryRouter>);
  const user = userEvent.setup();
  await user.click(await screen.findByRole('button', { name: 'Take out of service' }));
  await user.selectOptions(screen.getByLabelText('Reason'), 'repair');
  await user.type(screen.getByLabelText(/Staff note/), 'Replace worn bearing');
  await user.click(screen.getByRole('checkbox', { name: /physically stopped/ }));
  await user.click(screen.getByRole('button', { name: 'Confirm out of service' }));
  expect(await screen.findByText('Maintenance source is out of service. Review upcoming bookings below.')).toBeTruthy();
  expect(await screen.findByRole('heading', { name: 'Out of service' })).toBeTruthy();
  await user.click((await screen.findAllByRole('button', { name: 'Move', exact: true }))[0]);
  let dialog = within(screen.getByRole('dialog'));
  await waitFor(() => expect(dialog.getByRole('option', { name: /Maintenance replacement/ })).toBeTruthy());
  await user.selectOptions(dialog.getByLabelText('Replacement machine'), String(target));
  await user.click(dialog.getByRole('button', { name: 'Review move' }));
  expect(await dialog.findByText('$12.00/hr → $15.00/hr')).toBeTruthy();
  expect((await bridge.pool.query('SELECT equipmentid FROM reservation WHERE reservationid=$1', [bookings[0].reservationid])).rows[0].equipmentid).toBe(source);
  await user.click(dialog.getByRole('button', { name: 'Confirm move' }));
  expect(await screen.findByText('Booking moved. Confirmation follows the member’s email preferences.')).toBeTruthy();
  await user.click(await screen.findByRole('button', { name: 'Cancel booking' }));
  dialog = within(screen.getByRole('dialog'));
  await user.click(dialog.getByRole('button', { name: 'Confirm cancellation' }));
  expect(await screen.findByText('Booking cancelled. Confirmation follows the member’s email preferences.')).toBeTruthy();
  await user.click(await screen.findByRole('button', { name: 'Return to service' }));
  await user.type(screen.getByLabelText(/Completion note/), 'Bearing replaced and tested');
  fireEvent.submit(screen.getByLabelText(/Completion note/).closest('form')!);
  expect(await screen.findByText('Maintenance source is available again. Existing bookings are unchanged.')).toBeTruthy();
  const saved = (await bridge.pool.query('SELECT equipmentid,status FROM reservation WHERE reservationid=ANY($1) ORDER BY reservationid', [bookings.map(b => b.reservationid)])).rows;
  expect(saved).toEqual([{ equipmentid: target, status: 'confirmed' }, { equipmentid: source, status: 'cancelled' }]);
  const notices = (await bridge.pool.query("SELECT kind FROM app_notification_outbox WHERE payload->>'reservationId'=ANY($1) ORDER BY kind", [bookings.map(b => String(b.reservationid))])).rows;
  expect(notices.map(n => n.kind)).toEqual(['reservation_cancelled', 'reservation_updated']);
  expect((await bridge.pool.query('SELECT return_note FROM app_equipment_outage WHERE equipment_id=$1', [source])).rows[0].return_note).toBe('Bearing replaced and tested');
});
